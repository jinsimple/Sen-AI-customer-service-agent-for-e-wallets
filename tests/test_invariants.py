"""tests/test_invariants.py — FIN-05's hard constraints, as tests that actually run.

THE CORE DIFFERENCE from the usual way of writing invariant tests
-----------------------------------------------------------------
The common approach scans `src/` with regexes for suspicious function names
(`def .*refund.*`, `def .*lock_wallet.*`). That produces FALSE GREENS: if the code uses a
different name (here `approve_resolution`, not `execute_refund`), the regex matches nothing and
the test passes — passing because THERE WAS NOTHING TO CHECK, not because the code is right. A new
function violating HITL would slip through untouched.

This file does the opposite: **it introspects what is actually running and compares it with
`contracts/`**.

  - Authority  → reads `app.routes`, extracts `allowed_roles` from the closure of
                 `require_role()` at runtime, compares every route with the contract.
  - State      → reads the real `CheckConstraint`s in `src/db/models.py`,
                 compares their value sets with the contract.
  - Tools      → calls `build_customer_tools()` directly, compares tool names with the contract.

Consequence: add 1 route, change 1 guard, add 1 status value, rename 1 tool and forget to update
`contracts/` → RED IMMEDIATELY. Nobody has to remind anybody.

THERE IS NO pytest.skip HERE. A missing contract, table or tool = RED, not skipped. Silent skips
are exactly how an invariant suite slowly dies without anyone noticing.

If a test is red: either the code is wrong or the contract is wrong. DO NOT edit this file to match
the code — go back to the contract-change procedure in CLAUDE.md §3.

RUN:  pytest tests/test_invariants.py -v

Note: test function names and assertion messages are intentionally left in Vietnamese — they are
referenced verbatim from contracts/, ADRs and CI history.
"""

