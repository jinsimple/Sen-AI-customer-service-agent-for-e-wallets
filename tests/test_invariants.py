# HARD CONSTRAINT 1 (DB layer) — HITL enforced in the database, not just in code
# ===========================================================================

def _check_constraints() -> dict[str, str]:
    """Read every real CheckConstraint(name=...) in models.py via AST.

    AST instead of regex: it captures the call structure exactly and never mistakes strings in
    docstrings/comments for code.
    """
    tree = ast.parse(MODELS_PY.read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        fn = node.func
        if getattr(fn, "id", None) != "CheckConstraint" and getattr(fn, "attr", None) != "CheckConstraint":
            continue
        bieu_thuc = ""
        for arg in node.args:
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                bieu_thuc += arg.value
            elif isinstance(arg, ast.JoinedStr):
                bieu_thuc += "".join(
                    v.value for v in arg.values if isinstance(v, ast.Constant) and isinstance(v.value, str)
                )
        name_text = None
        for kw in node.keywords:
            if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                name_text = kw.value.value
        if name_text:
            out[name_text] = bieu_thuc
    return out


